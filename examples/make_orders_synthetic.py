"""Generate examples/orders_synthetic.csv: SYNTHETIC supplier orders for the ahp-bench walk-through.

Every value is invented by this script (seeded pseudo-random numbers); the suppliers, orders and numbers
do not describe real companies or transactions. Standard library only; only random.Random.random() is used
so that the output is the same on every Python 3 version.

python make_orders_synthetic.py [--out orders_synthetic.csv] [--seed 20261124] [--rows 400]
"""
from __future__ import annotations

import argparse
import csv
import io
import math
import random
from datetime import date, timedelta
from pathlib import Path

HEADER_NOTE = ("# SYNTHETIC DATA: invented supplier orders generated by make_orders_synthetic.py (seed {seed}); "
               "not real companies, orders or prices.")
COLUMNS = ["order_id", "order_date", "supplier", "category", "quantity", "unit_price", "discount_pct",
           "defective_units", "delivery_status", "lead_time_days", "compliance_check"]
# supplier: price factor, defect rate, P(late), P(cancelled), mean lead time (days), P(compliance fail), discount %
PROFILES = {
    "Supplier_A": (1.00, 0.020, 0.10, 0.05, 9.0, 0.05, 5.0),
    "Supplier_B": (0.92, 0.045, 0.22, 0.08, 12.0, 0.12, 7.0),
    "Supplier_C": (1.10, 0.012, 0.08, 0.04, 7.0, 0.04, 3.0),
    "Supplier_D": (0.97, 0.030, 0.15, 0.10, 10.0, 0.07, 6.0),
    "Supplier_E": (1.05, 0.025, 0.26, 0.05, 14.0, 0.05, 4.0),
}
CATEGORIES = {"Electronics": 42.0, "Packaging": 3.5, "Raw material": 11.0}


def generate(seed: int = 20261124, rows: int = 400) -> str:
    r = random.Random(seed)

    def pick(items):
        items = list(items)
        return items[min(int(r.random() * len(items)), len(items) - 1)]

    def normal(mu, sd):
        u1, u2 = max(r.random(), 1e-12), r.random()
        return mu + sd * math.sqrt(-2 * math.log(u1)) * math.cos(2 * math.pi * u2)

    buf = io.StringIO()
    buf.write(HEADER_NOTE.format(seed=seed) + "\n")
    w = csv.writer(buf, lineterminator="\n")
    w.writerow(COLUMNS)
    start = date(2026, 1, 5)
    for k in range(1, rows + 1):
        sup = pick(PROFILES)
        pf, defect, p_late, p_cancel, lead, p_fail, disc = PROFILES[sup]
        cat = pick(CATEGORIES)
        qty = int(20 + r.random() * 480)
        price = round(CATEGORIES[cat] * pf * (0.9 + 0.2 * r.random()), 2)
        u = r.random()
        status = "Cancelled" if u < p_cancel else ("Late" if u < p_cancel + p_late else "On time")
        if status == "Cancelled":
            defective, lead_days = 0, ""
        else:
            defective = max(0, int(round(normal(qty * defect, max(1.0, math.sqrt(qty * defect))))))
            extra = 4 + 6 * r.random() if status == "Late" else 0.0
            lead_days = str(max(2, int(round(normal(lead + extra, 2.0)))))
        discount = round(max(0.0, normal(disc, 1.5)), 1)
        check = "Fail" if r.random() < p_fail else "Pass"
        day = start + timedelta(days=int(r.random() * 300))
        w.writerow([f"PO-{k:04d}", day.isoformat(), sup, cat, qty, f"{price:.2f}", f"{discount:.1f}", defective,
                    status, lead_days, check])
    return buf.getvalue()


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--out", default=str(Path(__file__).with_name("orders_synthetic.csv")))
    ap.add_argument("--seed", type=int, default=20261124)
    ap.add_argument("--rows", type=int, default=400)
    a = ap.parse_args(argv)
    with open(a.out, "w", encoding="utf-8", newline="") as f:
        f.write(generate(a.seed, a.rows))
    print(f"wrote {a.out} ({a.rows} synthetic orders)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
