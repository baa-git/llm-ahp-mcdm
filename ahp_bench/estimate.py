"""Rough cost estimates for planned calls, from the study's recorded costs (no network access).

The reference is the cost actually billed per call in the study (the study's raw records, field `cost`),
divided by the number of questions in that call, per OpenRouter model id and condition. These per-question
costs are shipped in cost_reference.json (computed from the study records with `write_reference`), so no
study data is needed. A planned call is estimated as (reference cost per question) x (questions in the
planned call). Models without a reference record are reported as unknown and excluded from the total.
Prices change; treat the number as an order of magnitude, not a quote.
"""
from __future__ import annotations

import json
from collections import defaultdict
from pathlib import Path

from . import analysis as an

REFERENCE_FILE = Path(__file__).with_name("cost_reference.json")


def _load_reference() -> dict:
    if not REFERENCE_FILE.exists():
        return {"panel": [], "revision_panel": [], "judge": []}
    return json.loads(REFERENCE_FILE.read_text(encoding="utf-8"))


def _per_question(records, n_questions, key) -> dict:
    cost, q = defaultdict(float), defaultdict(int)
    for r in records:
        n = n_questions(r)
        if not n or not isinstance(r.get("cost"), (int, float)):
            continue
        k = key(r)
        cost[k] += float(r["cost"])
        q[k] += n
    return {k: cost[k] / q[k] for k in cost if q[k]}


def panel_reference(ref_dir=None) -> dict:
    """(model id, condition) -> USD per question for first-answer calls (direct/CoT); from the shipped
    reference file, or from the records in ref_dir (a raw records folder) when given."""
    if ref_dir is None:
        return {(m, c): v for m, c, v in _load_reference()["panel"]}
    recs, _ = an.load_records(Path(ref_dir) / "calls.jsonl")
    recs = [r for r in recs if r.get("condition") in ("lean", "cot") and r.get("parse_ok")]
    return _per_question(recs, lambda r: len(r.get("answers") or []), lambda r: (r.get("model_id"), r.get("condition")))


def revision_reference(ref_dir=None) -> tuple[dict, dict]:
    """((model id, condition) -> USD per question per revision call, judge model id -> USD per question
    per judge call); from the shipped reference file unless ref_dir is given."""
    if ref_dir is None:
        d = _load_reference()
        return {(m, c): v for m, c, v in d["revision_panel"]}, {m: v for m, v in d["judge"]}
    revs, _ = an.load_records(Path(ref_dir) / "revisions.jsonl")
    panel = _per_question(revs, lambda r: len(r.get("based_on_answers") or []),
                          lambda r: (r.get("model_id"), r.get("condition")))
    judges, _ = an.load_records(Path(ref_dir) / "judge_calls.jsonl")
    n_by_task = {"main": 10, "delivery": 6}  # study judge calls carry the task name only
    judge = _per_question(judges, lambda r: n_by_task.get(r.get("task")), lambda r: r.get("model_id"))
    return panel, judge


def write_reference(ref_dir, path=REFERENCE_FILE) -> dict:
    """Write cost_reference.json from a raw records folder (the study's results/raw)."""
    panel = panel_reference(ref_dir)
    rev_panel, judge = revision_reference(ref_dir)
    d = {"note": "USD per question billed in the study (OpenRouter usage.cost), per model id and condition key; "
                 "generated by ahp_bench.estimate.write_reference from the study's raw records.",
         "panel": [[m, c, panel[(m, c)]] for m, c in sorted(panel)],
         "revision_panel": [[m, c, rev_panel[(m, c)]] for m, c in sorted(rev_panel)],
         "judge": [[m, judge[m]] for m in sorted(judge)]}
    Path(path).write_text(json.dumps(d, indent=1) + "\n", encoding="utf-8", newline="\n")
    return d


def estimate(planned, reference) -> tuple[float, list]:
    """planned: iterable of (reference key, model label, n questions). Returns (USD total over the calls
    that have a reference, sorted list of model labels without a reference)."""
    total, unknown = 0.0, set()
    for key, label, n in planned:
        v = reference.get(key)
        if v is None:
            unknown.add(str(label))
        else:
            total += v * n
    return total, sorted(unknown)


def describe(total: float, unknown: list, n_calls: int) -> str:
    txt = f"estimated cost ~${total:.4f} for {n_calls} calls (from the study's billed cost per question"
    txt += "; prices change, so treat this as an order of magnitude)"
    if unknown:
        txt += f"; no reference for {', '.join(unknown)} (not included)"
    return txt
